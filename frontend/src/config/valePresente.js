export const textoVale = (idioma, chave, valores) => {
  const bruto = TEXTOS[idioma]?.[chave] ?? TEXTOS['pt-BR'][chave] ?? chave;
  if (!valores) return bruto;
  return bruto.replace(/\{(\w+)\}/g, (_, k) => (valores[k] !== undefined ? valores[k] : `{${k}}`));
};

export const LOCALE_VALE = { 'pt-BR': 'pt-BR', en: 'en-US', ja: 'ja-JP', es: 'es-ES' };

export const formatarDataVale = (iso, idioma) => {
  if (!iso) return '';
  const [a, m, d] = String(iso).slice(0, 10).split('-').map(Number);
  return new Date(a, m - 1, d).toLocaleDateString(LOCALE_VALE[idioma] || 'pt-BR');
};
