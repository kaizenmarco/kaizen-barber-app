export const ORIGEM_PUBLICA = (typeof window !== 'undefined' && window.location.hostname.endsWith('kaizenbarbershop.com'))
  ? 'https://app.kaizenbarbershop.com'
  : (typeof window !== 'undefined' ? window.location.origin : 'https://app.kaizenbarbershop.com');

export const linkDoVale = (codigo) => `${ORIGEM_PUBLICA}/valepresente/${codigo}`;

export const formatarIenes = (valor) => `¥${Number(valor || 0).toLocaleString('ja-JP')}`;

export const nomeServicoVale = (servicoId, nomeBanco, idioma) => {
  const s = servicoId ? getServicoPorUuid(servicoId) : null;
  return s ? getNomeServico(s, idioma) : (nomeBanco || '');
};

export const consultarVale = async (codigo) => {
  const { data, error } = await supabase.rpc('consultar_vale_presente', { p_codigo: codigo });
  if (error) throw error;
  return data;
};

export const buscarConfigVale = async () => {
  const { data, error } = await supabase.rpc('config_vale_presente_publica');
  if (error) throw error;
  return data;
};

