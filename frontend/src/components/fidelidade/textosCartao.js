export const traduzirCartao = (idioma, chave, valores) => {
  const dict = TEXTOS[idioma] || TEXTOS['pt-BR'];
  let texto = dict[chave] ?? TEXTOS['pt-BR'][chave] ?? chave;
  if (valores) {
    Object.entries(valores).forEach(([k, v]) => {
      texto = texto.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
  }
  return texto;
};

// Descrição do brinde/prêmio no idioma (config guarda pt/en/ja; es usa pt).
export const textoRecompensa = (mapa, idioma) => {
  if (!mapa) return '';
  if (idioma === 'en') return mapa.en || mapa.pt;
  if (idioma === 'ja') return mapa.ja || mapa.pt;
  return mapa.pt;
};

